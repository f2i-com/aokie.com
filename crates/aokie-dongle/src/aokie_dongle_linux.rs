//! Linux counterpart to `aokie_dongle` (which is Windows-only).
//!
//! Where the Windows `aokie_dongle` ships an INF + cat + cert bundle so
//! WinUSB binds to the dongle, on Linux every modern kernel already
//! exposes raw USB devices via libusb. The Linux pairing UX therefore
//! reduces to two questions:
//!
//!   1. **Can the user's account talk to the dongle?** Default udev
//!      rules give /dev/bus/usb nodes mode 0660 owned by root:plugdev
//!      — accounts not in the plugdev group can't open the device. We
//!      ship a udev rule that grants access to a specific VID:PID set
//!      (matching the dongle catalog) so the desktop user doesn't have
//!      to chmod 666 the bus.
//!
//!   2. **Is btusb holding the dongle?** The kernel's btusb driver
//!      claims interface 0 of every recognized Bluetooth dongle at
//!      plug-time. Our libusb transport detaches it on open(); the UX
//!      indicator just surfaces whether btusb is currently bound so
//!      the user can stop bluetoothd or unbind manually if needed.
//!
//! This file is the data-layer for those two — the udev rule renderer,
//! [`access`] (can this user open the dongle now), and [`install_rule`],
//! which puts the rule in place through pkexec (the desktop's own password
//! prompt) for `dongle.installDriver`, the setup screen's "Allow Aokie to
//! use the dongle".

#![cfg(target_os = "linux")]

use std::io::Write;
use std::path::PathBuf;
use std::process::{Command, Stdio};

// `DongleId` and the catalog live in `aokie_dongle_catalog` so the
// Windows WinUSB UX, the Linux udev path, and the frontend all
// resolve "is this an Aokie dongle?" against the same list. The
// re-exports here keep this module's public API stable for callers
// that already imported `aokie_dongle_linux::DongleId`.
pub use aokie_core::dongle_catalog::{DongleId, DEFAULT_CATALOG};

/// Render `/etc/udev/rules.d/70-aokie.rules` for a given catalog.
///
/// Default mechanism is `TAG+="uaccess"` only — systemd-logind grants
/// the device to whichever user is logged in at the local console
/// (R12-#11). On a single-user desktop that's exactly what we want:
/// the desktop user gets the dongle, headless / non-console users
/// don't. Aokie Bluetooth dongles aren't shared resources where you
/// want every account to be able to open them.
///
/// `permissive=true` adds `MODE="0666"` to each rule so any local
/// account can open the dongle (the previous default). Operators on
/// systems without working logind — kiosk distros, ssh-only headless
/// boxes, Wayland sessions where uaccess doesn't fire reliably — can
/// flip the `AOKIE_UDEV_PERMISSIVE=1` env on the frontend's "render
/// rule" call to fall back to the wider mode. Documented as a
/// belt-and-braces escape hatch, not the recommended path.
pub fn render_udev_rule(catalog: &[DongleId], permissive: bool) -> String {
    let mut out = String::new();
    out.push_str("# Generated by Aokie. Edit /etc/udev/rules.d/70-aokie.rules\n");
    out.push_str("# to revoke access; reload with `sudo udevadm control --reload-rules`.\n");
    out.push_str("#\n");
    out.push_str("# These rules grant the desktop user permission to open the\n");
    out.push_str("# Aokie Bluetooth dongle directly via libusb. They do NOT\n");
    out.push_str("# unbind btusb — the app does that per-session.\n");
    out.push_str("#\n");
    if permissive {
        out.push_str("# Permissive mode: rules include MODE=\"0666\" so any local\n");
        out.push_str("# account can open the dongle. Use only on kiosk / headless /\n");
        out.push_str("# non-logind systems where uaccess doesn't fire.\n");
    } else {
        out.push_str("# Standard mode: TAG+=\"uaccess\" hands the device to the\n");
        out.push_str("# user logged in at the local console (via systemd-logind).\n");
        out.push_str("# To grant access to additional accounts, regenerate the\n");
        out.push_str("# rule with permissive mode (MODE=0666) — see Aokie's\n");
        out.push_str("# Pairing → Advanced disclosure.\n");
    }
    out.push('\n');
    for id in catalog {
        if permissive {
            out.push_str(&format!(
                "SUBSYSTEM==\"usb\", ATTR{{idVendor}}==\"{:04x}\", \
                 ATTR{{idProduct}}==\"{:04x}\", MODE=\"0666\", \
                 TAG+=\"uaccess\"\n",
                id.vid, id.pid
            ));
        } else {
            out.push_str(&format!(
                "SUBSYSTEM==\"usb\", ATTR{{idVendor}}==\"{:04x}\", \
                 ATTR{{idProduct}}==\"{:04x}\", TAG+=\"uaccess\"\n",
                id.vid, id.pid
            ));
        }
    }
    out
}

/// Where the rule goes. Before 73: systemd-logind's `uaccess` builtin, which turns the `uaccess` tag into the
/// console user's access, runs from `73-seat-late.rules`, so a tag added by a later file (the `99-` this was) comes
/// too late and nobody is given the dongle. `70-`, beside systemd's own `70-uaccess.rules`.
pub fn udev_rule_path() -> &'static str {
    "/etc/udev/rules.d/70-aokie.rules"
}

/// The device node of a controller the transport names `usb:<bus>:<address>`
/// (`/dev/bus/usb/<bus>/<address>`, each three digits), or None for another name.
pub fn device_node(path: &str) -> Option<PathBuf> {
    let mut parts = path.strip_prefix("usb:")?.split(':');
    let (bus, address) = (parts.next()?.parse::<u8>().ok()?, parts.next()?.parse::<u8>().ok()?);
    parts.next().is_none().then(|| PathBuf::from(format!("/dev/bus/usb/{bus:03}/{address:03}")))
}

/// Whether this user can open a controller: what libusb needs to take it from `btusb` and drive it.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Access {
    /// Its node opens for reading and writing.
    Granted,
    /// It does not: the rule ([`install_rule`]) gives it to the user at the console.
    Needed,
    /// Not known (no node by that name, or another error).
    Unknown,
}

impl Access {
    pub fn as_str(self) -> &'static str {
        match self {
            Access::Granted => "granted",
            Access::Needed => "needed",
            Access::Unknown => "unknown",
        }
    }
}

/// [`Access`] to the controller at `path`. Opening its node claims nothing: the device is not touched, as the
/// transport's own listing does not.
pub fn access(path: &str) -> Access {
    let Some(node) = device_node(path) else { return Access::Unknown };
    match std::fs::OpenOptions::new().read(true).write(true).open(&node) {
        Ok(_) => Access::Granted,
        Err(e) if e.kind() == std::io::ErrorKind::PermissionDenied => Access::Needed,
        Err(_) => Access::Unknown,
    }
}

/// Put `rule` at [`udev_rule_path`] as root, through pkexec (the desktop's own password prompt), and have udev
/// apply it to the dongle `vid`:`pid` now, so that the dongle plugged in is the user's without unplugging it. The
/// rule goes in on standard input and the ids as arguments: nothing the caller gave is part of the script. `Err`
/// when pkexec is missing, the person cancels, or a step fails, with what it said.
pub fn install_rule(rule: &str, vid: u16, pid: u16) -> Result<(), String> {
    const SCRIPT: &str = "set -e; umask 022; cat > \"$1\"; udevadm control --reload-rules; \
        udevadm trigger --action=change --subsystem-match=usb --attr-match=idVendor=\"$2\" --attr-match=idProduct=\"$3\"";
    let mut child = Command::new("pkexec")
        .args(["/bin/sh", "-c", SCRIPT, "aokie-udev", udev_rule_path(), &format!("{vid:04x}"), &format!("{pid:04x}")])
        .stdin(Stdio::piped())
        .stdout(Stdio::null())
        .stderr(Stdio::piped())
        .spawn()
        .map_err(|e| format!("pkexec could not be started ({e}): put the rule at {} by hand, as root", udev_rule_path()))?;
    child
        .stdin
        .take()
        .ok_or("pkexec took no input")?
        .write_all(rule.as_bytes())
        .map_err(|e| format!("the rule was not handed to pkexec: {e}"))?;
    let out = child.wait_with_output().map_err(|e| format!("pkexec: {e}"))?;
    match out.status.code() {
        Some(0) => Ok(()),
        // pkexec: 126, the person dismissed the prompt or was not authorised; 127, no authentication agent.
        Some(126) => Err("the password prompt was cancelled: nothing was changed".into()),
        Some(127) => Err(format!("no password prompt could be shown here (no polkit agent): put the rule at {} by hand, as root", udev_rule_path())),
        _ => Err(format!("putting the rule in place failed: {}", String::from_utf8_lossy(&out.stderr).trim())),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use aokie_core::dongle_catalog::DongleCompatTier;

    #[test]
    fn render_udev_rule_emits_one_line_per_catalog_entry() {
        let catalog = &[
            DongleId {
                vid: 0x0a5c,
                pid: 0x21e8,
                tier: DongleCompatTier::Certified,
            },
            DongleId {
                vid: 0x0bda,
                pid: 0x8771,
                tier: DongleCompatTier::Beta,
            },
        ];
        let rule = render_udev_rule(catalog, false);
        let lines: Vec<&str> = rule
            .lines()
            .filter(|l| l.starts_with("SUBSYSTEM"))
            .collect();
        assert_eq!(lines.len(), 2);
        assert!(lines[0].contains("0a5c"));
        assert!(lines[0].contains("21e8"));
        assert!(lines[1].contains("0bda"));
        assert!(lines[1].contains("8771"));
    }

    #[test]
    fn standard_mode_uses_uaccess_only_no_world_rw() {
        let rule = render_udev_rule(DEFAULT_CATALOG, false);
        assert!(rule.contains("TAG+=\"uaccess\""));
        assert!(
            !rule.contains("MODE=\"0666\""),
            "standard mode must not grant world-rw — that's the permissive override"
        );
    }

    #[test]
    fn permissive_mode_adds_world_rw_for_kiosk_setups() {
        let rule = render_udev_rule(DEFAULT_CATALOG, true);
        assert!(rule.contains("TAG+=\"uaccess\""));
        assert!(rule.contains("MODE=\"0666\""));
    }

    #[test]
    fn a_controllers_node_is_its_bus_and_address_in_three_digits() {
        assert_eq!(device_node("usb:3:5"), Some(PathBuf::from("/dev/bus/usb/003/005")));
        assert_eq!(device_node("usb:1:120"), Some(PathBuf::from("/dev/bus/usb/001/120")));
        assert_eq!(device_node("usb:1"), None);
        assert_eq!(device_node("usb:1:2:3"), None);
        assert_eq!(device_node("usb:x:2"), None);
        assert_eq!(device_node("\\\\?\\usb#vid_0a5c"), None);
        assert_eq!(access("usb:255:255"), Access::Unknown, "no such node");
    }

    #[test]
    fn render_udev_rule_starts_with_a_doc_comment_block() {
        let rule = render_udev_rule(DEFAULT_CATALOG, false);
        let first = rule.lines().next().unwrap();
        assert!(first.starts_with("# Generated by Aokie"));
    }
}
